"""Typed deterministic SQL tools shared by native graph backends."""

from datetime import date, datetime
from decimal import Decimal

from experiments.validation.runtime.native_graph import Scalar


def python_type(kind):
    kind = kind.upper()
    if kind == "BOOLEAN":
        return bool
    if "INT" in kind:
        return int
    if kind.startswith("DECIMAL"):
        return Decimal
    if kind == "DATE":
        return date
    if kind.startswith("TIMESTAMP"):
        return datetime
    if kind in {"DOUBLE", "REAL", "FLOAT"}:
        return float
    return str


class Predicate:
    __name__ = "deterministic_sql_predicate"

    def __init__(self, expression, fields):
        self.scalar = Scalar({"keep": expression}, fields)
        self.__name__ = "predicate_" + self.scalar.__name__

    def __call__(self, row):
        return self.scalar(row)["keep"] is True


def context_frame(frame, options):
    if options["distinct"]:
        frame = frame.drop_duplicates()
    for name, ascending, nulls_first in reversed(options["order"]):
        frame = frame.sort_values(
            name,
            ascending=ascending,
            na_position="first" if nulls_first else "last",
            kind="stable",
        )
    if options["limit"] is not None:
        frame = frame.head(options["limit"])
    return frame.reset_index(drop=True)


class SQLJoin:
    """Ordinary SQL hash join as Nirvana's deterministic join tool."""

    __name__ = "deterministic_sql_join"

    def __init__(self, keys, *, left_columns=None, right_columns=None):
        self.keys = keys
        self.left_columns = left_columns
        self.right_columns = right_columns

    def __call__(self, left, right):
        return all(
            left[a] is not None and right[b] is not None and left[a] == right[b]
            for a, b in self.keys
        )

    def frames(self, left, right):
        # Nirvana's native operators may retain columns excluded by a SQL
        # projection. Only remove conflicting leaked columns; keep temporary
        # fields generated by native map rewrites, which may be consumed by a
        # filter above this join.
        if self.left_columns is not None and self.right_columns is not None:
            overlap = set(left.columns) & set(right.columns)
            left = left.drop(columns=sorted(overlap - set(self.left_columns)))
            right = right.drop(columns=sorted(overlap - set(self.right_columns)))
            ambiguous = set(left.columns) & set(right.columns)
            if ambiguous:
                raise ValueError(
                    f"SQL join has ambiguous internal fields: {sorted(ambiguous)}"
                )
        if not self.keys:
            return left.merge(right, how="cross")
        a, b = map(list, zip(*self.keys))
        left = left.loc[left[a].notna().all(axis=1)]
        right = right.loc[right[b].notna().all(axis=1)]
        return left.merge(right, left_on=a, right_on=b, how="inner").reset_index(
            drop=True
        )


def reference_counts(node):
    """Count graph references, preserving repeated edges of shared CTEs."""
    counts = {}

    def visit(current):
        counts[id(current)] = counts.get(id(current), 0) + 1
        for child in current.children:
            visit(child)

    visit(node)
    return counts
